export function isVowel(id: LetterId): boolean {
  return LETTERS[id].kind === 'vowel';
}

export function isLetterId(ch: string): ch is LetterId {
  return (UKRAINIAN_ALPHABET as readonly string[]).includes(ch);
}

export function toUpper(text: string): string {
  return text.toLocaleUpperCase('uk-UA');
}

export function toLower(text: string): string {
  return text.toLocaleLowerCase('uk-UA');
}

/** Розкладає текст на букви абетки (апостроф і пробіли ігноруються, інші символи - помилка). */
export function lettersOf(text: string): LetterId[] {
  const result: LetterId[] = [];
  for (const ch of toUpper(text)) {
    if (' ’\'.,!?-'.includes(ch)) continue;
    if (!isLetterId(ch)) {
      throw new Error(`Символ «${ch}» (U+${ch.codePointAt(0)?.toString(16).toUpperCase()}) у «${text}» не є українською буквою`);
    }
    result.push(ch);
  }
  return result;
}

/** Чи можна прочитати текст, знаючи лише ці букви. */
export function isReadableWith(text: string, letters: Iterable<LetterId>): boolean {
  const allowed = new Set(letters);
  return lettersOf(text).every((l) => allowed.has(l));
}
